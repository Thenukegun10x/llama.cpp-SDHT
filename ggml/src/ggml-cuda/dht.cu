// Orthonormal discrete Hartley transform of one row. cas(t) = cos(t) + sin(t), so
// DHT = Re(FFT) - Im(FFT). One block per row, N/2 threads run one butterfly each.
template <int N, typename T>
__global__ __launch_bounds__(N/2) void dht_cuda(const T * src, float * dst, const int64_t n_rows, const float scale) {
    constexpr int LG = N == 64 ? 6 : N == 128 ? 7 : N == 256 ? 8 : 9;

    __shared__ float2 s[N];

    const int64_t r = blockIdx.x;
    if (r >= n_rows) {
        return;
    }
    src += r * N;
    dst += r * N;

    const int tid = threadIdx.x;

    ggml_cuda_pdl_sync();

    for (int j = tid; j < N; j += N/2) {
        s[__brev((unsigned) j) >> (32 - LG)] = make_float2(ggml_cuda_cast<float>(src[j]), 0.0f);
    }
    __syncthreads();

    for (int step = 1; step < N; step *= 2) {
        const int j  = tid & (step - 1);
        const int a  = (tid / step) * (2 * step) + j;
        const int b  = a + step;
        const float2 aa = s[a];
        const float2 bb = s[b];
        const float2 tw = dht_twiddle[j * (256 / step)];
        const float br = bb.x * tw.x - bb.y * tw.y;
        const float bi = bb.x * tw.y + bb.y * tw.x;
        s[a] = make_float2(aa.x + br, aa.y + bi);
        s[b] = make_float2(aa.x - br, aa.y - bi);
        __syncthreads();
    }

    for (int j = tid; j < N; j += N/2) {
        dst[j] = (s[j].x - s[j].y) * scale;
    }
}

template <typename T>
static bool ggml_cuda_op_dht_impl(ggml_backend_cuda_context & ctx, const ggml_tensor * src, ggml_tensor * dst) {
    const int     n    = src->ne[0];
    const int64_t rows = ggml_nrows(src);

    const T * src_d = (const T *) src->data;
    float *   dst_d = (float *) dst->data;

    cudaStream_t stream = ctx.stream();

    const float scale     = 1.0f / sqrtf((float) n);
    const dim3  grid_dims(rows, 1, 1);

#define DHT_LAUNCH(N)                                                                 \
    {                                                                                 \
        const dim3 block_dims(N/2, 1, 1);                                             \
        const ggml_cuda_kernel_launch_params lp =                                     \
            ggml_cuda_kernel_launch_params(grid_dims, block_dims, 0, stream);         \
        ggml_cuda_kernel_launch(dht_cuda<N, T>, lp, src_d, dst_d, rows, scale);       \
        return true;                                                                  \
    }

    switch (n) {
        case 64:  DHT_LAUNCH(64)
        case 128: DHT_LAUNCH(128)
        case 256: DHT_LAUNCH(256)
        case 512: DHT_LAUNCH(512)
        default:  return false;
    }

#undef DHT_LAUNCH
}

bool ggml_cuda_op_mul_mat_use_dht(const struct ggml_tensor * op) {
    const struct ggml_tensor * a = op->src[0];
    const struct ggml_tensor * b = op->src[1];

    return op->op == GGML_OP_MUL_MAT && ggml_get_op_params_i32(op, 1) == GGML_HINT_SRC0_IS_HARTLEY &&
           a->type == GGML_TYPE_F32 && op->type == GGML_TYPE_F32 &&
           (b->type == GGML_TYPE_F32 || b->type == GGML_TYPE_F16) && ggml_is_contiguous(b) && ggml_is_contiguous(op) &&
           ggml_are_same_shape(b, op);
}

bool ggml_cuda_op_dht(ggml_backend_cuda_context & ctx, const struct ggml_tensor * src, struct ggml_tensor * dst) {
    GGML_ASSERT(ggml_are_same_shape(src, dst));

    if (!ggml_is_contiguous(src) || !ggml_is_contiguous(dst)) {
        return false;
    }
    if (dst->type != GGML_TYPE_F32) {
        return false;
    }

    switch (src->type) {
        case GGML_TYPE_F32:
            return ggml_cuda_op_dht_impl<float>(ctx, src, dst);
        case GGML_TYPE_F16:
            return ggml_cuda_op_dht_impl<half>(ctx, src, dst);
        default:
            return false;
    }
}
